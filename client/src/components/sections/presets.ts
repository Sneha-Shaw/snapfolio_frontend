import type { SiteSection } from '@/types/models';

export interface LayoutPreset {
  id: string;
  name: string;
  description: string;
  /** Shown with a "Best" badge in the admin. */
  recommended?: boolean;
  /** Built on the newest (✦) section designs — shown first with a "New" badge. */
  modern?: boolean;
  /** Built on the ◆ premium section designs — listed first with a gold badge. */
  premium?: boolean;
  /**
   * Set when the preset is built for a specific line of work — the admin
   * groups these separately and shows the label on the card.
   */
  profession?: string;
  /**
   * Set when the preset is built around a motif (web, comic, tree, …) rather
   * than a trade or a mood. Listed in its own group in the admin.
   */
  concept?: string;
  /** Footer design this preset ships with (see site/footers.tsx). */
  footer?: string;
  /** Theme preset applied alongside, when the admin opts in. */
  theme: string;
  sections: [SiteSection, string][];
}

