/* Keep picker metadata lightweight; design implementations load on demand. */
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const folder = path.resolve(__dirname, '../src/components/sections');
const families = ['hero', 'about', 'projects', 'experience', 'education', 'skills', 'services', 'stats', 'testimonials', 'gallery', 'contact', 'divider', 'modern', 'premium', 'nature', 'objects', 'environments', 'weather', 'macbook', 'analog', 'makers', 'science', 'signature'];
let output = `// Generated by scripts/generate-section-catalog.cjs. Edit the source variant lists.\nimport { lazy } from 'react';\nimport type { SectionVariant } from './shared';\n\nfunction deferred(load: () => Promise<Record<string, unknown>>, group: string, id: string) {\n  return lazy(async () => {\n    const variants = (await load())[group] as SectionVariant[];\n    const variant = variants.find(v => v.id === id);\n    if (!variant) throw new Error(\x60Unknown section variant: \${group}/\${id}\x60);\n    return { default: variant.Component };\n  });\n}\n`;
let count = 0;
for (const family of families) {
  const source = ts.createSourceFile(`${family}.tsx`, fs.readFileSync(path.join(folder, `${family}.tsx`), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  // Families like signature.tsx build each group from a shared `designs` list: `export const X: SectionVariant[] = variants('hero')`.
  let designs;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const decl of statement.declarationList.declarations) {
      if (decl.name.getText(source) !== 'designs' || !decl.initializer) continue;
      const init = ts.isAsExpression(decl.initializer) ? decl.initializer.expression : decl.initializer;
      if (ts.isArrayLiteralExpression(init)) designs = init;
    }
  }
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement) || !statement.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
    for (const decl of statement.declarationList.declarations) {
      if (decl.type?.getText(source) !== 'SectionVariant[]' || !decl.initializer) continue;
      const list = ts.isArrayLiteralExpression(decl.initializer) ? decl.initializer
        : ts.isCallExpression(decl.initializer) && decl.initializer.expression.getText(source) === 'variants' ? designs : undefined;
      if (!list) continue;
      const group = decl.name.getText(source);
      const entries = list.elements.map(element => {
        if (!ts.isObjectLiteralExpression(element)) throw new Error(`Expected literal metadata in ${group}`);
        const metadata = {};
        for (const property of element.properties) {
          if (!ts.isPropertyAssignment(property)) continue;
          const name = property.name.getText(source);
          if (['id', 'name', 'description'].includes(name)) {
            if (!ts.isStringLiteral(property.initializer)) throw new Error(`Expected literal ${group}.${name}`);
            metadata[name] = property.initializer.text;
          }
        }
        if (!metadata.id || !metadata.name) throw new Error(`Missing variant metadata: ${group}`);
        count++;
        return `  { ...${JSON.stringify(metadata)}, Component: deferred(() => import('./${family}'), '${group}', ${JSON.stringify(metadata.id)}) }`;
      });
      output += `\nexport const ${group}: SectionVariant[] = [\n${entries.join(',\n')}\n];\n`;
    }
  }
}
const target = path.join(folder, 'variantCatalog.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fs.writeFileSync(target, output);
console.log(`Section catalog: ${count} deferred designs across ${families.length} families.`);
